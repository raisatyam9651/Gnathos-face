<h3 class="font-headline-sm text-xl text-primary mb-3">Muscle Spasm and Trismus</h3>
<p class="text-on-surface-variant">Involuntary contraction of jaw muscles, often from dental issues, trauma, or infection, restricting mouth opening.</p>
</div>
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant hover-lift">
