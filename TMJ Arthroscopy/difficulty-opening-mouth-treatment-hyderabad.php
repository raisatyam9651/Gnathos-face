</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Physical therapy is often highly effective for mouth opening problems. Treatment includes jaw exercises to stretch and strengthen muscles, manual therapy to mobilize the joint, and thermal modalities. Most patients see significant improvement within 6-8 weeks.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
