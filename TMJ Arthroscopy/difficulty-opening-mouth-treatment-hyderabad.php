<p class="text-on-surface-variant">When the articular disc becomes displaced, it can block jaw opening, causing limited mouth opening or lock jaw.</p>
</div>
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant hover-lift">
