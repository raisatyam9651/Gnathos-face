<div class="text-center mb-12">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Frequently Asked Questions</h2>
<p class="text-on-surface-variant">Common concerns about jaw popping treatment.</p>
</div>
<div class="space-y-4">
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What causes jaw popping sounds?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Jaw popping sounds are typically caused by disc displacement within the TMJ, joint inflammation, or muscle tension affecting how the joint moves. The sound occurs when the disc shifts position or when bones glide over rough surfaces.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Is jaw popping serious?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Jaw popping by itself may not be serious, especially if it's painless. However, it can indicate an underlying TMJ problem that may worsen over time. If accompanied by pain, locking, or limited movement, evaluation by a specialist is recommended.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can jaw popping be cured?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Many cases of jaw popping can be significantly improved or resolved with proper treatment. Conservative approaches work well for many patients. For persistent cases, TMJ arthroscopy can provide lasting relief by addressing the underlying disc problem.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Why does my jaw pop when I chew?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Chewing places significant stress on the TMJ. If there's disc displacement or joint inflammation, the increased pressure during chewing can cause the disc to shift, creating a popping sound. Avoiding hard foods and seeking treatment can help.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How can I stop my jaw from popping?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Avoid hard and chewy foods, practice good jaw posture, reduce stress, use a night guard if you grind your teeth, and apply warm compresses. If popping persists or worsens, consult a TMJ specialist for proper diagnosis and treatment.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    When should I see a doctor for jaw popping?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
See a specialist if jaw popping is accompanied by pain, locking, limited opening, or if the sounds are worsening over time. Also seek evaluation if popping significantly affects your ability to eat or speak comfortably.
                </div>
