<div class="space-y-4">
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What causes jaw inflammation?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Jaw inflammation can be caused by TMJ synovitis (joint lining inflammation), muscle inflammation from overuse or clenching, trauma to the jaw, arthritis, infections, or autoimmune conditions affecting the joint.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How do I reduce jaw inflammation at home?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Apply ice packs to the side of the face for 15-20 minutes several times a day, eat soft foods, avoid excessive jaw movements, take over-the-counter anti-inflammatory medications, and practice jaw relaxation techniques.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How long does jaw inflammation last?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Mild jaw inflammation may resolve within a few days to a week with conservative care. More severe inflammation may take several weeks. Chronic conditions may require ongoing management to prevent flare-ups.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Is jaw inflammation serious?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
While often temporary and treatable, persistent or recurrent jaw inflammation can lead to joint damage over time. If accompanied by fever, significant swelling, or difficulty opening the mouth, prompt evaluation is recommended.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can stress cause jaw inflammation?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Yes, stress can contribute to jaw inflammation through increased clenching and grinding, which puts stress on the TMJ and jaw muscles. Stress management and protective appliances like night guards can help.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    When should I see a doctor for jaw inflammation?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
See a specialist if jaw swelling is severe or worsening, accompanied by fever, causing significant difficulty opening the mouth, persistent for more than a week, or recurrent despite home care.
