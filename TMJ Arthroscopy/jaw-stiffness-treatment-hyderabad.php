</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Jaw stiffness typically results from muscle tension caused by teeth grinding or clenching (bruxism), stress and anxiety, poor posture, TMJ disorders, or trauma. Often, multiple factors contribute to the condition.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How is jaw stiffness diagnosed?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Diagnosis involves clinical examination to assess jaw movement, muscle tenderness, and joint function. We evaluate your bite, check for teeth wear patterns, and assess muscle tension levels. Imaging may be recommended if joint pathology is suspected.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can jaw stiffness be treated without surgery?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Yes, most cases of jaw stiffness respond well to conservative treatment including physical therapy, stress management, appliance therapy, and medications. Surgery or botulinum toxin injections are considered for cases that don't respond to conservative treatment.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What is botulinum toxin treatment for jaw stiffness?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Botulinum toxin (Botox) injections target the masseter and temporalis muscles to relax overactive jaw muscles. This treatment is effective for severe bruxism and muscle hypertrophy causing jaw stiffness. Effects typically last 3-4 months.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How effective is physical therapy for jaw stiffness?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Physical therapy is often highly effective for jaw stiffness. Treatment includes jaw exercises, manual therapy to release muscle tension, heat therapy, posture correction, and relaxation techniques. Most patients experience significant improvement within 4-8 weeks.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How can I prevent jaw stiffness?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Prevention strategies include managing stress through relaxation techniques, avoiding chewy foods that strain the jaw, practicing good posture, using a night guard if you grind your teeth, and performing regular jaw stretching exercises.
