<!-- Patient FAQs -->
<section class="py-section-gap bg-surface-container-low">
<div class="max-w-3xl mx-auto px-margin-mobile md:px-margin-desktop">
<div class="text-center mb-12">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Frequently Asked Questions</h2>
<p class="text-on-surface-variant">Common concerns about limited mouth opening.</p>
</div>
<div class="space-y-4">
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Why can't I open my mouth fully?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Inability to open the mouth fully can be caused by TMJ locking (disc displacement), muscle spasm, joint inflammation, arthritis, or fibrosis. Your specialist will determine the exact cause through examination and imaging.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What is normal mouth opening?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Normal mouth opening is typically 35-55mm, which equals about 3 finger widths placed between the upper and lower front teeth. Anything less than 30mm is generally considered restricted.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How can I improve my mouth opening?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Gentle jaw exercises, heat therapy, physical therapy, and gradual stretching can help. However, if restriction is severe or worsening, evaluation by a TMJ specialist is recommended for proper treatment.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can TMJ cause locked jaw?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Yes, TMJ disorders commonly cause jaw locking, either open lock (can't close) or closed lock (can't open). This is often due to disc displacement or joint inflammation and can usually be treated effectively.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Is limited mouth opening an emergency?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Sudden complete inability to open the mouth can be distressing but is rarely a medical emergency. However, persistent or worsening limitation should be evaluated promptly to prevent further joint damage.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    When should I see a specialist for mouth opening problems?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
See a specialist if you can't open your mouth more than 30mm, have complete inability to open, the restriction is worsening, or if it's accompanied by severe pain, clicking, or joint swelling.
                </div>
</details>
