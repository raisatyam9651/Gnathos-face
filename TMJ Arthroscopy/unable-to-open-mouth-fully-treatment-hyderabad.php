<div class="text-center mb-12">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Frequently Asked Questions</h2>
<p class="text-on-surface-variant">Common concerns about inability to open mouth fully.</p>
</div>
<div class="space-y-4">
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Why can't I open my mouth fully?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Inability to open the mouth fully can be caused by TMJ disc displacement (closed lock), jaw muscle spasm, joint inflammation, arthritis, post-surgical changes, or other TMJ pathology. A proper evaluation is needed to determine the exact cause.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What is a normal mouth opening?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Normal mouth opening is typically 35-55mm, which equals about 3 finger widths placed between the upper and lower front teeth. Anything less than 30mm is generally considered restricted and should be evaluated.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can I force my mouth open if I can't open it fully?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Forcing your jaw open can cause further damage and worsen the condition. It's best to gently try to open within your comfort range and seek professional evaluation if the restriction persists.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How can I improve my mouth opening at home?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Gentle jaw exercises, heat therapy to the jaw area, eating soft foods, and avoiding excessive jaw movements may help. However, if the restriction is significant or worsening, professional evaluation is recommended.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What happens if I don't treat my restricted mouth opening?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Untreated restricted mouth opening can lead to difficulty eating and speaking, nutritional deficiencies, poor oral hygiene, muscle atrophy, joint damage, and permanent reduction in jaw mobility. Early treatment is important.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    When should I see a doctor for restricted mouth opening?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
See a specialist if you cannot open your mouth more than 30mm, have complete inability to open, the restriction is worsening, or if it's accompanied by severe pain, swelling, or clicking.
                </div>
