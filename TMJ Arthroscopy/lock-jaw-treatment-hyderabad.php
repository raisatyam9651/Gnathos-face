<div class="text-center mb-12">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Frequently Asked Questions</h2>
<p class="text-on-surface-variant">Common concerns about lock jaw treatment and recovery.</p>
</div>
<div class="space-y-4">
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What causes lock jaw?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Lock jaw is typically caused by displacement of the articular disc in the TMJ. When the disc moves out of its normal position, it can become lodged in front of the jaw joint, preventing normal opening. This often follows clicking jaw that progresses to complete disc displacement.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Is lock jaw an emergency?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Lock jaw can be a distressing condition but is rarely a medical emergency. However, if you cannot close your jaw (open lock) or have significant difficulty opening (closed lock), you should seek evaluation promptly. Open lock, where you cannot close your jaw, typically requires more urgent intervention.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
