<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What causes facial pain?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Facial pain can be caused by TMJ disorders, muscle tension from teeth grinding or clenching, stress, poor posture, joint inflammation, arthritis, nerve conditions like trigeminal neuralgia, or trauma to the face or jaw.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How is facial pain diagnosed?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Diagnosis involves detailed medical history, physical examination of jaw movement and muscle tenderness, assessment of joint sounds and bite, and imaging studies such as CBCT or MRI when needed to evaluate joint and soft tissue structures.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can facial pain be treated without surgery?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Yes, most cases of facial pain respond well to conservative treatment including physical therapy, medications, stress management, and appliance therapy. Surgical options are reserved for cases that don't respond to conservative treatment.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What is the difference between TMJ pain and trigeminal neuralgia?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
TMJ pain is typically a dull, aching pain in the jaw joint and surrounding muscles, often worse with jaw movement. Trigeminal neuralgia causes sharp, shooting, electric shock-like pain along the distribution of the trigeminal nerve, often triggered by light touch or eating.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How effective is physical therapy for facial pain?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Physical therapy is highly effective for many types of facial pain. Treatment includes jaw exercises, manual therapy to release muscle tension, heat therapy, and relaxation techniques. Most patients experience significant improvement within 4-8 weeks.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How long does facial pain treatment take?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Treatment duration depends on the cause and severity. With conservative management, significant improvement is often seen within 4-8 weeks. Some patients may need longer-term management for chronic conditions. Your specialist will provide a personalized treatment timeline.
