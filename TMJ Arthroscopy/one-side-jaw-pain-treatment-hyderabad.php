                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
While one-sided jaw pain is often not serious, persistent or worsening pain should be evaluated by a specialist. It can indicate an underlying TMJ condition, dental issue, or muscle problem that may improve with proper treatment.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How do you treat jaw pain on one side?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Treatment depends on the cause. Conservative options include anti-inflammatory medications, physical therapy, heat/cold therapy, and night guards. Advanced treatments include trigger point injections, botulinum toxin, and TMJ arthroscopy for more severe cases.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
