<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What is a TMJ disorder and what causes it?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
TMJ disorders affect the temporomandibular joint that connects your jaw to your skull. Causes include disc displacement, arthritis, joint inflammation, teeth grinding, stress, trauma, and misalignment. Often, multiple factors contribute to TMJ problems.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How are TMJ disorders diagnosed?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
TMJ disorders are diagnosed through comprehensive clinical examination assessing jaw movement, pain, clicking, and locking. Imaging such as CBCT, MRI, and CT scans provides detailed evaluation of joint structures and disc position.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can TMJ disorders be treated without surgery?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
