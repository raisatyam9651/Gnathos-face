<div class="text-center mb-12">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Frequently Asked Questions</h2>
<p class="text-on-surface-variant">Common concerns about jaw locking treatment.</p>
</div>
<div class="space-y-4">
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Why does my jaw keep locking?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Jaw locking is usually caused by disc displacement within the TMJ. When the disc moves out of its normal position, it can prevent the condyle from moving smoothly, causing the jaw to lock. This can recur until the underlying disc problem is addressed.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What should I do when my jaw locks?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Stay calm, avoid forcing your jaw open wider, try gentle jaw movements, apply a warm compress, and contact your TMJ specialist. If the lock persists for more than a day or is accompanied by severe pain, seek prompt evaluation.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-anglejustify-between p-6 cursor-pointer font-semibold text-primary">
                    Can jaw locking be cured?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
While the underlying disc displacement may not be completely reversible, jaw locking can be effectively managed and significantly reduced with proper treatment. Many patients achieve long periods without locking episodes.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Is jaw locking an emergency?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
While distressing, most jaw locking is not a medical emergency. However, open lock (inability to close) should be evaluated relatively promptly. Closed lock can often be managed at home initially but should be evaluated within a few days if it doesn't resolve.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What is closed lock jaw?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Closed lock is the most common type of jaw locking where you cannot open your mouth fully or at all. It's caused by the articular disc being displaced forward and not returning to its normal position, blocking the joint's movement.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    When should I see a doctor for jaw locking?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
See a specialist if jaw locking occurs more than once, lasts more than 24-48 hours, is accompanied by severe pain, is getting worse over time, or if you've been managing it with home care without improvement.
