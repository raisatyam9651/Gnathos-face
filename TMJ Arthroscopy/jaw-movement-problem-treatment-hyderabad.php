<!-- Patient FAQs -->
<section class="py-section-gap bg-surface-container-low">
<div class="max-w-3xl mx-auto px-margin-mobile md:px-margin-desktop">
<div class="text-center mb-12">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Frequently Asked Questions</h2>
<p class="text-on-surface-variant">Common concerns about jaw movement problems.</p>
</div>
<div class="space-y-4">
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What causes jaw deviation when opening mouth?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Jaw deviation to one side during opening is often caused by disc displacement within the TMJ. When the disc is displaced, the condyle cannot glide smoothly, causing the jaw to shift toward the affected side. This can also result from muscle imbalance or joint inflammation.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Is jaw deviation serious?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Jaw deviation can range from mild to severe. Mild deviation may not cause significant problems, but moderate to severe deviation often indicates underlying TMJ pathology that can worsen over time. Proper diagnosis and treatment are recommended.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can jaw movement problems be fixed?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Many jaw movement problems can be significantly improved or resolved with proper treatment. The success depends on the underlying cause, severity, and how early treatment is sought. Early intervention leads to better outcomes.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Why does my jaw feel stuck when opening?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
A stuck or catching sensation during jaw opening can be caused by disc displacement, joint inflammation, muscle spasm, or loose bone fragments within the joint. Your specialist can identify the specific cause through examination and imaging.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How can I improve my jaw movement?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Gentle jaw exercises, heat therapy, avoiding hard foods, and practicing good jaw posture can help. However, if you have significant movement problems or worsening symptoms, evaluation by a TMJ specialist is recommended.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    When should I see a doctor for jaw movement problems?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
See a specialist if you notice significant jaw deviation, have catching or locking during opening, experience restricted opening less than 30mm, or if the movement problem is accompanied by pain or clicking.
                </div>
</details>
