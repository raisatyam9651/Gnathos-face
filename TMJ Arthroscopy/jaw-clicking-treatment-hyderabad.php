<div class="text-center mb-16">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Understanding Jaw Clicking and Popping Sounds</h2>
<p class="font-body-lg text-body-lg text-on-surface-variant max-w-2xl mx-auto">
                Jaw clicking and popping sounds occur when the disc within the temporomandibular joint (TMJ) moves out of its normal position. Understanding the cause is essential for effective treatment.
            </p>
</div>
<div class="grid md:grid-cols-3 gap-8">
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant hover-lift">
<span class="material-symbols-outlined text-4xl text-secondary mb-4 icon-fill-1">warning</span>
<h3 class="font-headline-sm text-xl text-primary mb-3">TMJ Internal Derangement</h3>
<p class="text-on-surface-variant">When the articular disc becomes displaced, clicking or popping sounds occur as the jaw moves. This may or may not be accompanied by pain.</p>
</div>
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant hover-lift">
<span class="material-symbols-outlined text-4xl text-secondary mb-4 icon-fill-1">fitness_center</span>
<h3 class="font-headline-sm text-xl text-primary mb-3">Muscle Hyperactivity</h3>
<p class="text-on-surface-variant">Teeth grinding (bruxism) or clenching can cause muscle spasms and joint sounds. Stress and poor posture often contribute to this condition.</p>
</div>
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant hover-lift">
<span class="material-symbols-outlined text-4xl text-secondary mb-4 icon-fill-1">coronavirus</span>
<h3 class="font-headline-sm text-xl text-primary mb-3">Joint Degeneration</h3>
<p class="text-on-surface-variant">Osteoarthritis or degenerative changes in the joint can create clicking, popping, or crepitus (grinding sounds) during jaw movement.</p>
</div>
</div>
