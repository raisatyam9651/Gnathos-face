<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Is jaw clicking serious? Should I be worried?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Not all jaw clicking requires treatment. If clicking is painless and occasional, it may not need intervention. However, if clicking is accompanied by pain, limited opening, or if it progresses to jaw locking, evaluation by a TMJ specialist is recommended. Changes in your bite or increasing frequency of sounds warrant assessment.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
