<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What causes jaw clicking and popping sounds?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
Jaw clicking occurs when the articular disc in the TMJ becomes displaced or moves out of its normal position. As the jaw opens and closes, the disc may click or pop as it repositions. Causes include trauma, teeth grinding, stress, arthritis, and naturally occurring disc displacement.
                </div>
