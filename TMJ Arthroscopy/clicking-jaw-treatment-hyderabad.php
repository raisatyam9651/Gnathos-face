<!-- Understanding Jaw Clicking -->
<section class="py-section-gap bg-surface-container-low">
<div class="max-w-container-max mx-auto px-margin-mobile md:px-margin-desktop">
<div class="text-center mb-16">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Understanding Jaw Clicking</h2>
<p class="font-body-lg text-body-lg text-on-surface-variant max-w-2xl mx-auto">
                Jaw clicking occurs when the temporomandibular joint (TMJ) makes sounds during movement. While sometimes harmless, clicking can indicate underlying joint dysfunction.
            </p>
</div>
<div class="grid md:grid-cols-3 gap-8">
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant">
<span class="material-symbols-outlined text-4xl text-secondary mb-4 icon-fill-1">move_item</span>
<h3 class="font-headline-sm text-xl text-primary mb-3">Disc Displacement with Reduction</h3>
<p class="text-on-surface-variant">The articular disc moves out of position and returns with a clicking sound. Often accompanied by mild symptoms.</p>
</div>
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant">
<span class="material-symbols-outlined text-4xl text-secondary mb-4 icon-fill-1">vibration</span>
<h3 class="font-headline-sm text-xl text-primary mb-3">Hyper mobility</h3>
<p class="text-on-surface-variant">Excessive joint movement due to stretched ligaments. Causes clicking and sometimes jaw locking.</p>
</div>
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant">
<span class="material-symbols-outlined text-4xl text-secondary mb-4 icon-fill-1">breakfast_dining</span>
<h3 class="font-headline-sm text-xl text-primary mb-3">Crepitus</h3>
<p class="text-on-surface-variant">Grating or crunching sounds caused by joint surface damage, often from arthritis or degeneration.</p>
</div>
</div>
</div>
</section>

