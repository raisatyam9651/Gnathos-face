<h3 class="font-headline-sm text-primary">Pre &amp; Post-Surgical Orthodontics</h3>
</div>
<ul class="space-y-6">
<li>
<h4 class="font-semibold text-primary mb-2">Pre-Surgical Alignment</h4>
<p class="text-on-surface-variant text-sm mb-2">Orthodontic treatment to align the teeth over the underlying bone in preparation for surgical repositioning. This typically involves leveling the arches, coordinating tooth widths, and eliminating crowding or spacing to ensure the surgical segments fit together precisely.</p>
<p class="text-on-surface-variant text-sm"><strong>Duration:</strong> 12–18 months on average</p>
</li>
<li>
<h4 class="font-semibold text-primary mb-2">Post-Surgical Detailing</h4>
<p class="text-on-surface-variant text-sm mb-2">Fine-tuning the bite after the jaws have healed in their new, correct positions. This phase ensures intercuspal seating—the perfect contact between upper and lower teeth—with ideal overbite and overjet relationships.</p>
<p class="text-on-surface-variant text-sm"><strong>Duration:</strong> 6–12 months depending on complexity</p>
</li>
<li>
<h4 class="font-semibold text-primary mb-2">Arch Coordination</h4>
<p class="text-on-surface-variant text-sm">Ensuring the upper and lower dental arches are properly aligned in width and form. This prevents crossbite tendencies post-surgery and ensures smooth chewing function.</p>
</li>
<li>
<h4 class="font-semibold text-primary mb-2">Debonding & Retention</h4>
<p class="text-on-surface-variant text-sm">Once alignment is finalized, braces are removed and retainers are fitted to maintain the new bite. Custom Hawley or clear retainers help preserve stability as the bone continues to remodel.</p>
</li>
</ul>
