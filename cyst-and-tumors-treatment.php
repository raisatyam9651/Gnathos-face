<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Are all oral cysts and tumors cancerous?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    No. The majority of oral cysts are benign and respond well to surgical removal. While some oral lesions can be precancerous or malignant, early detection and treatment offer excellent outcomes. A biopsy provides definitive diagnosis to guide appropriate treatment.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Will I need general anesthesia for cyst removal?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Treatment is typically performed under local anesthesia with sedation or under general anesthesia, depending on the lesion size, location, and complexity. Your surgeon will discuss the most appropriate anesthesia option during your pre-operative consultation. Small lesions can often be removed under local anesthesia alone.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
