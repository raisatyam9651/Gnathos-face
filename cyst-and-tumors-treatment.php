                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Histopathology results are typically available within 5-7 working days. For urgent cases or during surgery, frozen section analysis can provide preliminary results within 20-30 minutes. Your treating team will contact you with results and discuss the next steps in your treatment plan.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can oral cysts recur after removal?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Some cyst types have a higher recurrence rate than others. Complete enucleation with careful removal of the cyst lining significantly reduces recurrence risk. Certain aggressive lesions like ameloblastomas may require more extensive surgery or long-term monitoring. Your surgeon will explain the specific recurrence risk for your diagnosis.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
