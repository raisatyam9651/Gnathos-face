                    </summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                        Upper eyelid surgery typically takes 45-60 minutes, while combined upper and lower blepharoplasty may take 2-3 hours. Ptosis repair adds 30-45 minutes depending on complexity. The procedure is usually performed as day surgery, with patients going home the same day.
                    </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
