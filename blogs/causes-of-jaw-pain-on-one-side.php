                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                How do I know if it's TMJ or a tooth problem?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                TMJ pain often worsens with jaw movement, chewing, or yawning and is felt in front of the ear. Tooth pain is usually localised, sharp, and triggered by hot/cold/biting. When in doubt, see a specialist for a clear diagnosis.
                            </p>
                        </details>
                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                Can heart problems cause pain on one side of the jaw?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Yes — especially on the left side. Cardiac pain can radiate to the jaw, neck, and arm. Combined with chest pain, sweating, or breathlessness, this is a medical emergency — call an ambulance.
                            </p>
                        </details>
                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                Is one-sided jaw pain a sign of cancer?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Rarely. Persistent unexplained jaw pain, especially with a lump, ulcer, or numbness, should be evaluated. See <a href="/blogs/what-are-the-symptoms-of-oral-cancer/" class="font-semibold text-secondary">oral cancer symptoms</a> for warning signs.
                            </p>
                        </details>
