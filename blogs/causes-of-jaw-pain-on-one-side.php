                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                See someone within a week if the pain is moderate to severe, persistent, or affecting your sleep or eating. See someone today if there are red-flag symptoms.
                            </p>
                        </details>
