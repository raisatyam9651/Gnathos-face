                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Yes. Stress-related clenching or grinding often affects one side more than the other. A night guard, jaw exercises, and stress management are first-line treatments.
                            </p>
