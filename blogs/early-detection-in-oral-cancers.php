                    <h2 id="screening" class="scroll-mt-24">Screening and the Dentist's Role</h2>
                    <p>
                        Screening means looking for cancer before symptoms appear. Population-based screening programs in India have shown that visual inspection by trained workers can reduce mortality in high-risk groups.
                    </p>
                    <p>
                        Opportunistic screening happens every time you visit a dentist. A thorough oral cancer check takes less than two minutes and should be part of every routine dental visit.
                    </p>
                    <p>
                        Your dentist is often the first person to spot a suspicious area. Dentists trained in oral medicine and maxillofacial specialists carry out a structured head and neck examination and refer onward when needed.
                    </p>
                    <p>
                        If you are not sure <a href="what-type-of-doctor-do-i-need-to-see-for-tmj.php" class="text-secondary underline-offset-4 hover:underline">which doctor to consult</a> for a mouth lesion, start with your dentist or a maxillofacial surgeon. They will guide the next steps.
                    </p>
                    <p>
                        Knowing <a href="difference-between-a-dentist-and-a-maxillofacial-surgeon.php" class="text-secondary underline-offset-4 hover:underline">a maxillofacial surgeon's training</a> helps you understand who is best placed to evaluate and biopsy a suspicious oral lesion.
                    </p>

                    <h2 id="workup" class="scroll-mt-24">Diagnostic Workup and Imaging</h2>
                    <p>
                        When a lesion looks suspicious, the clinician may first use toluidine blue staining. This dye highlights abnormal cells and helps identify the best site to sample.
                    </p>
                    <p>
                        A brush biopsy collects cells from the surface of the lesion using a small brush. It is quick, painless, and useful as a screening aid, though a positive result still needs confirmation.
                    </p>
                    <p>
                        An incisional biopsy remains the gold standard. A small piece of tissue is removed under local anaesthesia and sent for histopathological examination. This gives a definitive diagnosis.
                    </p>
                    <p>
                        Imaging helps assess the extent of disease. Ultrasound of the neck is used to evaluate lymph nodes. CT or MRI gives detailed information about bone and soft tissue involvement.
                    </p>
                    <p>
                        PET-CT is reserved for advanced cases. It helps identify distant spread and guides treatment planning for stage III and IV disease.
                    </p>

