                    <h2 id="warning-signs" class="scroll-mt-24">Early Warning Signs</h2>
                    <p>
                        A non-healing ulcer that persists beyond two weeks is the classic red flag. Most traumatic ulcers from biting or burns heal within ten to fourteen days.
                    </p>
                    <p>
                        Any new red or white patch inside the mouth, on the tongue, or on the gums deserves attention. Patches that change in size, colour, or surface texture are particularly concerning.
                    </p>
                    <p>
                        A persistent lump or thickening in the cheek, tongue, floor of the mouth, or neck should not be ignored. Difficulty opening the mouth, swallowing, or moving the tongue can also be early signs.
                    </p>
                    <p>
                        Persistent hoarseness, unexplained numbness of the tongue or lip, and loose teeth without an obvious dental cause can all signal an underlying malignancy. If any of these persist beyond two weeks, see a specialist.
                    </p>
                    <p>
                        Recognising <a href="what-are-the-symptoms-of-oral-cancer.php" class="text-secondary underline-offset-4 hover:underline">oral cancer symptoms</a> early gives you the best chance of a complete cure. The disease is far easier to treat when it is small.
                    </p>

