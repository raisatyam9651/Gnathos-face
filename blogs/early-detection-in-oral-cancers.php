                    <h2 id="two-week-rule" class="scroll-mt-24">The Two-Week Rule</h2>
                    <p>
                        The two-week rule is simple. Any ulcer, patch, or lump inside the mouth that has not healed in two weeks must be examined by a qualified clinician. There are no exceptions.
                    </p>
                    <p>
                        This rule exists because most benign mouth sores resolve within a week or two. Anything that lingers is statistically more likely to be serious.
                    </p>
                    <p>
                        Acting on this rule is the single most powerful step a patient can take. It compresses the delay between first symptom and diagnosis, which is where most lives are saved.
                    </p>

                    <h2 id="self-exam" class="scroll-mt-24">Self-Examination at Home</h2>
                    <p>
                        You can examine your own mouth once a month in good light. Stand in front of a mirror and use a torch. Wash your hands and remove any dentures before you begin.
                    </p>
                    <p>
                        First, look at your face and neck for any swelling or asymmetry. Feel along both sides of your neck and under your jaw for lumps.
                    </p>
                    <p>
                        Pull your cheeks out and inspect the inner lining on both sides. Look at the gums, the floor of the mouth under your tongue, and the roof of your mouth.
                    </p>
                    <p>
                        Stick your tongue out and inspect the top, sides, and underside. Use a gauze to hold the tip and turn the tongue to see the back edges.
                    </p>
                    <p>
                        Finally, feel the inside of your cheeks and the floor of the mouth with a clean finger. Note any tenderness, thickening, or change in texture.
                    </p>
                    <p>
                        A regular self-exam helps you learn what is normal for you. You are then more likely to notice something new. If you are unsure about what you are feeling, compare both sides.
                    </p>

