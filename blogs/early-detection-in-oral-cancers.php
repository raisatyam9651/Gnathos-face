                    <h2 id="burden" class="scroll-mt-24">The Burden of Oral Cancer in India</h2>
                    <p>
                        India carries one of the heaviest burdens of oral cancer in the world. It accounts for roughly one third of all oral cancers diagnosed globally each year, and it ranks among the most common cancers in Indian men.
                    </p>
                    <p>
                        The disease is most often diagnosed between the ages of 40 and 65, but younger adults are increasingly affected. Most cases are linked to tobacco use, which makes the disease, in a very real sense, preventable.
                    </p>
                    <p>
                        The tragedy is that most patients still present at an advanced stage, when surgery is extensive and survival is poor. Early detection offers a way out of this pattern. A lesion caught at stage I can be treated with a small operation and excellent outcomes.
                    </p>

                    <div class="aspect-[16/9] w-full rounded-2xl overflow-hidden shadow-lg border border-surface-container-high my-10">
