                    <h2 id="risk-factors" class="scroll-mt-24">Risk Factors You Should Know</h2>
                    <p>
                        Tobacco in any form is the single biggest risk factor. This includes smoking cigarettes, bidis, chillums, and hookah, as well as smokeless forms such as gutka, khaini, zarda, and mishri.
                    </p>
                    <p>
                        Betel nut, often chewed as paan with or without tobacco, is independently carcinogenic. Regular use of betel quid causes changes in the lining of the mouth long before cancer develops.
                    </p>
                    <p>
                        Heavy alcohol consumption raises the risk further, especially when combined with tobacco. The two together multiply the danger rather than simply add to it.
                    </p>
                    <p>
                        Human papillomavirus, particularly HPV 16, is now a recognised cause of oropharyngeal cancers. Vaccination against HPV can lower this risk substantially.
                    </p>
                    <p>
                        Chronic sun exposure increases the risk of lip cancers, especially on the lower lip. People who work outdoors for long hours should use lip protection.
                    </p>

                    <h2 id="premalignant" class="scroll-mt-24">Pre-Malignant Lesions</h2>
                    <p>
                        Some oral lesions are not cancer but carry a meaningful risk of becoming cancer. Identifying and monitoring these is a cornerstone of early detection.
                    </p>
                    <p>
                        Leukoplakia appears as a white patch that cannot be scraped off and is not explained by any other disease. The risk of malignant transformation varies with the appearance and site.
                    </p>
                    <p>
                        Erythroplakia is a red, velvety patch that looks more aggressive than leukoplakia. It carries a much higher malignant potential and warrants prompt biopsy.
                    </p>
                    <p>
                        Oral submucous fibrosis is common in India and is strongly linked to areca nut use. Patients develop stiff cheeks, reduced mouth opening, burning on eating, and altered tongue movement.
                    </p>
                    <p>
                        Lichen planus of the mouth can sometimes show dysplastic change. Any persistent, asymmetric, or ulcerated area within lichen planus should be reviewed by a specialist.
                    </p>

