                    <h2 id="what-is" class="scroll-mt-24">What Is Facial Trauma?</h2>

                    <p>
                        Facial trauma refers to any injury to the soft tissues, bones, teeth or sensory organs of the face. It results from road traffic accidents, falls, assaults, sports injuries, animal bites and burns.
                    </p>

                    <p>
                        In India, road traffic crashes remain the single largest cause of facial injuries. Two-wheeler riders without helmets, occupants without seatbelts and pedestrians hit by fast-moving vehicles contribute heavily to the national burden.
                    </p>

                    <p>
                        Beyond the immediate pain, facial trauma affects how you breathe, see, speak, chew and smile. It also carries a strong psychosocial weight because the face is central to identity. Timely, specialist-led care preserves both function and appearance.
                    </p>

                    <div class="aspect-[16/9] w-full rounded-2xl overflow-hidden shadow-lg border border-surface-container-high my-10">
