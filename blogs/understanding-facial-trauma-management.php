                    <h2 id="patterns" class="scroll-mt-24">Common Injury Patterns</h2>

                    <p>
                        Facial injuries fall into clear anatomical groups. Each pattern demands a different surgical strategy and recovery plan.
                    </p>

                    <h3>Soft Tissue Injuries</h3>

                    <p>
                        Lacerations, abrasions, bite wounds and burns involve the skin, underlying muscle and sometimes nerves. Meticulous cleaning, layered closure and tetanus prophylaxis are essential.
                    </p>

                    <p>
                        Bite wounds, both human and animal, carry a high infection risk and need antibiotic cover. Burns require dressing, fluid management and long-term scar surveillance.
                    </p>

                    <h3>Dentoalveolar Injuries</h3>

                    <p>
                        Dentoalveolar injuries involve the teeth and the bone that supports them. They include tooth avulsion, subluxation, intrusion and fracture of the alveolar bone.
                    </p>

                    <p>
                        An avulsed permanent tooth should be replanted within sixty minutes if possible. Milk or saline are preferred transport media. Splinting follows for two to four weeks.
                    </p>

                    <p>
                        Alveolar fractures are often seen with dental injuries or with <a href="symptoms-of-impacted-wisdom-tooth.php">impacted wisdom teeth</a> that have weakened the surrounding bone.
                    </p>

                    <h3>Mandibular Fractures</h3>

                    <p>
                        The mandible is the most commonly fractured facial bone. Fractures are described by their location: symphyseal, parasymphyseal, body, angle, ramus, condyle and coronoid.
                    </p>

                    <p>
                        Recognising <a href="broken-jaw-symptoms.php">broken jaw symptoms</a> early, such as malocclusion, pain on biting, numbness of the lower lip and limited mouth opening, speeds up referral.
                    </p>

                    <p>
                        Condylar fractures may be treated conservatively with a short period of maxillomandibular fixation and guided physiotherapy, especially in growing patients. Displaced body and angle fractures usually need open surgery.
                    </p>

                    <h3>Midface and Le Fort Fractures</h3>

                    <p>
                        Midface fractures follow predictable patterns described by Rene Le Fort. A Le Fort I fracture separates the palate from the upper face. A Le Fort II passes through the nasal bones and maxilla in a pyramid shape. A Le Fort III is a complete craniofacial disjunction.
                    </p>

                    <p>
                        Patients typically present with a flattened midface, mobile upper jaw, epistaxis and malocclusion. Surgical correction often involves <a href="what-is-orthognathic-surgery.php">orthognathic surgery</a> principles to re-establish facial height and projection.
                    </p>

                    <h3>Zygomaticomaxillary Complex Fractures</h3>

                    <p>
                        The zygoma, or cheekbone, articulates with the maxilla, frontal bone, temporal bone and sphenoid. A fracture at all four articulations is called a ZMC or "tripod" fracture.
                    </p>

                    <p>
                        Classic signs include a flattened cheek prominence, infra-orbital nerve numbness, trismus and subconjunctival haemorrhage. Fixation typically needs three or more plates to stabilise the zygoma.
                    </p>

                    <h3>Orbital Fractures</h3>

                    <p>
                        Orbital floor "blowout" fractures occur when a sudden rise in intra-orbital pressure ruptures the thin floor into the maxillary sinus. Tissue can herniate into the sinus.
                    </p>

                    <p>
                        A "trapdoor" fracture in children can entrap the inferior rectus muscle and needs urgent release. Indications for repair include diplopia, enophthalmos and large floor defects on imaging.
                    </p>

                    <h3>Nasal Fractures</h3>

                    <p>
                        The nose is the most frequently injured facial structure. Fractures may be isolated or part of a broader midface injury.
                    </p>

                    <p>
                        Closed reduction within ten days works well for simple displaced fractures. Complex nasal injuries with septal involvement may need a formal septorhinoplasty later.
                    </p>

                    <h3>Frontal Sinus and Skull Base</h3>

                    <p>
                        High-energy impacts can fracture the frontal sinus and the anterior skull base. CSF rhinorrhoea, forehead depression and pneumocephalus are warning signs.
                    </p>

                    <p>
                        These injuries need a combined approach with neurosurgery to seal the dura and obliterate or cranialise the frontal sinus when indicated.
                    </p>

