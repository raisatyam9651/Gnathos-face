                    <h2 id="timing" class="scroll-mt-24">Timing and Principles of Surgery</h2>

                    <p>
                        Not every facial fracture needs immediate surgery. Timing depends on the patient's general condition, swelling, associated injuries and the specific fracture pattern.
                    </p>

                    <p>
                        Immediate surgery is reserved for airway compromise, uncontrolled bleeding, open fractures, entrapment of the eye muscle and contaminated wounds. Delayed surgery, usually after swelling settles at five to ten days, is common for elective facial reconstruction.
                    </p>

                    <p>
                        Staged surgery is used for complex injuries. Initial surgery controls damage, while later stages address bone defects, scarring and any need for <a href="what-is-orthognathic-surgery.php">orthognathic surgery</a> refinement.
                    </p>

                    <p>
                        The central surgical principle is Open Reduction and Internal Fixation, known as ORIF. The fracture is exposed, fragments are anatomically repositioned and stabilised with plates and screws.
                    </p>

                    <p>
                        Plates come in many sizes. Mini-plates suit the midface, mandibular angle and orbit. Reconstruction plates bridge large mandibular defects. Resorbable plates are useful in growing children where permanent hardware is undesirable.
                    </p>

                    <h2 id="post-op" class="scroll-mt-24">Post-Operative Care and Recovery</h2>

                    <p>
                        Recovery after facial fracture surgery is a structured journey. Most patients stay in hospital for one to three days, depending on the injuries treated.
                    </p>

                    <p>
                        A soft diet is prescribed for four to six weeks. Oral hygiene is reinforced with chlorhexidine rinses. Antibiotics, analgesics and anti-inflammatory medicines are tailored to the procedure.
                    </p>

                    <p>
                        Cold compresses help in the first forty-eight hours. Head elevation reduces swelling. Avoid blowing the nose after orbital or sinus surgery to prevent surgical emphysema.
                    </p>

                    <p>
                        For a day-by-day guide, read our detailed page on <a href="recovery-time-after-jaw-surgery-complete-healing-timeline-and-care-tips.php">recovery after jaw surgery</a>, which covers jaw wiring, splints and physiotherapy timelines.
                    </p>

                    <p>
                        Open discussion about <a href="side-effects-of-maxillofacial-surgery-risks-complications-and-prevention.php">maxillofacial surgery risks</a> helps you recognise early warning signs such as persistent fever, worsening pain, sudden swelling or visual change.
                    </p>

