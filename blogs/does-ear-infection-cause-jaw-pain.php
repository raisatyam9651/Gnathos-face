                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                If you have fever, hearing loss, or ear discharge, see an ENT first. If your symptoms worsen with chewing, yawning, or jaw movement, see a maxillofacial specialist first. Many patients end up seeing both.
                            </p>
