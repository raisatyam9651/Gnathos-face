                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                Can an ear infection make your jaw swell?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Yes. Severe ear infections can cause swelling in front of and below the ear, sometimes making the jaw look puffy. If swelling is significant, see a specialist the same day to rule out <a href="/blogs/symptoms-of-jaw-infection-after-the-root-canal/" class="font-semibold text-secondary">jaw infection</a> or abscess.
                            </p>
                        </details>
                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                Why do I get ear and jaw pain when I chew?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Chewing moves the TMJ, and the joint's movement can pull on the ear canal and middle-ear structures. If the joint is inflamed or the disc is displaced, chewing reproduces the pain.
                            </p>
                        </details>
                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                Can wisdom teeth cause ear and jaw pain?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Yes — impacted lower wisdom teeth are a classic cause of referred ear-jaw pain on the same side. See <a href="/blogs/symptoms-of-impacted-wisdom-tooth/" class="font-semibold text-secondary">impacted wisdom tooth symptoms</a> and <a href="/blogs/can-wisdom-teeth-cause-tmj/" class="font-semibold text-secondary">whether wisdom teeth cause TMJ</a>.
                            </p>
                        </details>
                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                How long does ear-infection jaw pain last?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Acute ear infections usually clear up within 7–14 days with appropriate treatment. Referred jaw pain resolves as the ear heals. If jaw pain persists after the ear is better, a separate TMJ evaluation is needed.
                            </p>
                        </details>
                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                Can TMJ cause an ear infection?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Not directly. But chronic TMJ inflammation can block the eustachian tube (which runs near the joint), leading to fluid build-up in the middle ear that mimics or predisposes to infection.
                            </p>
                        </details>
                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                Can swimmer's ear cause jaw pain?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Yes. Otitis externa inflames the ear canal, and the inflammation can spread to the TMJ in front of it. Pulling on the earlobe typically reproduces the pain.
                            </p>
                        </details>
                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                Is tinnitus a sign of TMJ or ear infection?
                                <span class="material-symbols-outlined group-open:rotate-180 transition-transform text-secondary">expand_more</span>
                            </summary>
                            <p class="mt-4 font-body-md text-on-surface-variant leading-relaxed">
                                Both can cause it. Tinnitus with ear pain and fever points to ear infection; tinnitus with jaw clicking and chewing pain points to TMJ. A specialist can distinguish quickly.
                            </p>
                        </details>
                        <details class="group border border-surface-container-high rounded-xl bg-surface-container-lowest p-6 cursor-pointer open:bg-surface-container-low transition-colors shadow-sm">
                            <summary class="font-headline-sm text-primary text-[18px] flex justify-between items-center list-none font-semibold">
                                Should I see an ENT or a maxillofacial surgeon first?
