                    <h2 id="what-is" class="scroll-mt-24">What Counts as Cosmetic Facial Surgery</h2>
                    <p>
                        Cosmetic facial surgery refers to procedures performed to enhance the appearance of the face, jaw, and neck. The goal is aesthetic improvement, although many of these procedures also restore function.
                    </p>
                    <p>
                        It sits apart from reconstructive surgery, which is done to repair defects from trauma, cancer, or congenital conditions. Cosmetic procedures are broadly grouped into surgical and non-surgical options. Surgical options change structure. Non-surgical options improve surface, contour, and skin quality without an operating room visit.
                    </p>
                    <p>
                        At Gnathos, we often see patients who need both. A weak chin, a long face, or a gummy smile may need skeletal correction. Fine lines, pigmentation, and early jowling may respond to non-surgical care. A complete plan usually blends the two. This is what we mean by going beyond the basics, looking at the face as a whole rather than chasing a single feature.
                    </p>

                    <div class="aspect-[16/9] w-full rounded-2xl overflow-hidden shadow-lg border border-surface-container-high my-10">
