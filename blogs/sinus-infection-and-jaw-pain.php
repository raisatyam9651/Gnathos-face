                    <h2 id="specialist" class="scroll-mt-24">When to See a Maxillofacial Specialist</h2>
                    <p>While minor sinus pressure resolves on its own, you should consult a maxillofacial or ENT specialist if:</p>
                    <ul>
                        <li>Your jaw pain persists for more than 10-14 days despite using decongestants or antihistamines.</li>
                        <li>You have localized swelling on your gums, cheek, or jawline.</li>
                        <li>You experience fever, severe headaches, visual disturbances, or swelling around your eyes.</li>
                        <li>You suspect your sinus infection was caused by a dental issue (odontogenic sinusitis). Up to 40% of chronic maxillary sinus infections are caused by an infected tooth root that has broken through the sinus floor.</li>
                    </ul>

                    <h2 id="treatment" class="scroll-mt-24">Treatment and Recovery</h2>
                    <p>For sinus-induced jaw pain, relief starts by clearing the sinus passages:</p>
                    <ul>
                        <li><strong>Hydration and Steam:</strong> Drinking plenty of fluids and inhaling steam to thin nasal secretions.</li>
                        <li><strong>Nasal Irrigation:</strong> Flushing the sinuses with sterile saline using a Neti pot.</li>
                        <li><strong>Decongestants and Mucolytics:</strong> Medications to shrink swollen nasal tissues and break up thick mucus.</li>
                        <li><strong>Antibiotic Therapy:</strong> If a specialist diagnoses a bacterial sinus infection, a course of antibiotics may be prescribed.</li>
                        <li><strong>Dental Treatment:</strong> If the sinus infection is odontogenic (caused by a tooth root infection), treating the tooth via root canal or extraction is required to clear the sinus.</li>
                    </ul>

