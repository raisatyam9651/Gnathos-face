                    <h2 id="procedure" class="scroll-mt-24">The Procedure</h2>

                    <p>
                        MMA is performed under general anaesthesia. You will be asleep for the entire operation. A nasal tube is used so the surgeon has full access to both jaws.
                    </p>

                    <p>
                        All incisions are placed inside the mouth. There are no visible scars on the face. The Le Fort I osteotomy frees the maxilla at the level of the piriform aperture, and the BSSO splits the mandibular ramus bilaterally.
                    </p>

                    <p>
                        Both jaws are mobilised and brought forward according to the pre-operative VSP. Prefabricated splints guide the new bite. Titanium miniplates and screws fix the bones in their new position. The incisions are closed with resorbable sutures.
                    </p>

                    <p>
                        Operating time is usually 2 to 4 hours, depending on the magnitude of movement and whether adjunctive procedures (such as genioglossus advancement or septoplasty) are added. Most patients stay in hospital for 1 to 2 nights.
                    </p>

                    <p>
                        If you want a deeper look at the technical background, our explainer on the <a href="/blogs/what-is-orthognathic-surgery-purpose-procedure-and-recovery-explained/">purpose, procedure and recovery of orthognathic surgery</a> walks through each step in detail.
                    </p>

                    <h2 id="recovery" class="scroll-mt-24">Recovery and Healing</h2>

                    <p>
                        The first 24 to 48 hours focus on swelling control, pain management, and monitoring. You will be on a liquid diet and your jaw will feel stiff. Cold compresses and a head-elevated position help reduce swelling quickly.
                    </p>

                    <p>
                        Over the first two weeks, swelling peaks around day three and then begins to recede. You will continue with liquids and progress to soft foods by the end of week two. Most patients return to desk work in about 10 to 14 days.
                    </p>

                    <p>
                        Numbness in the lower lip and chin is common in the early weeks. It usually improves over three to six months as the inferior alveolar nerve recovers. We monitor nerve function at every follow-up.
                    </p>

                    <p>
                        Full bony union takes about six to eight weeks. By three months, most patients are eating normally and have resumed exercise. Final facial settling continues for up to a year. Detailed milestones are mapped in our <a href="/blogs/recovery-time-after-jaw-surgery-complete-healing-timeline-and-care-tips/">recovery timeline</a> guide.
                    </p>

