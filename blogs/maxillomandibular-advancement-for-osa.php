                    <h2 id="what-is-mma" class="scroll-mt-24">What is Maxillomandibular Advancement</h2>

                    <p>
                        Maxillomandibular advancement, often shortened to MMA, is a combined <a href="/blogs/what-is-orthognathic-surgery/">orthognathic surgery</a> that moves both the upper jaw (maxilla) and the lower jaw (mandible) forward by about 8 to 12 millimetres.
                    </p>

                    <p>
                        The upper jaw is repositioned through a Le Fort I osteotomy. The lower jaw is repositioned through a bilateral sagittal split osteotomy (BSSO). Both jaws are then fixed in their new position with titanium plates and screws.
                    </p>

                    <p>
                        Because the tongue and soft palate are anchored to the jaws, advancing the bones pulls the entire soft-tissue envelope of the airway forward. The retropalatal and retrolingual spaces enlarge at the same time. The result is a stable, three-dimensional enlargement of the upper airway.
                    </p>

                    <p>
                        MMA is considered the most effective surgical treatment for OSA, with success rates higher than any other single procedure. It is the operation we turn to when CPAP and lesser procedures have failed.
                    </p>

