                    <h2 id="candidates" class="scroll-mt-24">Who is a Candidate for MMA</h2>

                    <p>
                        You are a strong candidate for MMA when conservative treatments have not worked. The most common reason patients reach our clinic is failure of CPAP, the gold-standard non-surgical therapy.
                    </p>

                    <p>
                        You may also be a candidate if your apnoea–hypopnoea index (AHI) is moderate to severe. Most surgeons recommend MMA once AHI crosses 15 events per hour, particularly when accompanied by daytime symptoms.
                    </p>

                    <p>
                        Other indicators include an elevated BMI (typically under 35 for surgical safety), a retrusive maxilla or mandible, and a crowded posterior airway seen on imaging. We confirm the site and pattern of collapse with drug-induced sleep endoscopy before recommending surgery.
                    </p>

                    <p>
                        If you are unsure whether your jaw position contributes to your symptoms, our guide on <a href="/blogs/can-jaw-surgery-help-with-sleep-apnea/">jaw surgery for sleep apnoea</a> explains how anatomy and apnoea are linked.
                    </p>

                    <h2 id="pre-op" class="scroll-mt-24">Pre-Operative Workup</h2>

                    <p>
                        No patient goes into MMA without a structured workup. The cornerstone is a level-1 polysomnography, which gives us your AHI, oxygen saturation nadir, and sleep architecture.
                    </p>

                    <p>
                        We then perform drug-induced sleep endoscopy (DISE). Under light sedation, a flexible endoscope records the exact level and direction of airway collapse. DISE tells us whether MMA is the right procedure or whether a site-specific alternative would serve you better.
                    </p>

                    <p>
                        Imaging follows. A cone-beam CT (CBCT) maps your facial skeleton, while lateral cephalometric analysis quantifies your jaw relationships, airway length, and hyoid position. Together they feed the virtual surgical plan.
                    </p>

                    <p>
                        Finally, we build a 3D virtual surgical plan (VSP) on dedicated software. The plan models bone cuts, vector of movement, nerve position, and final occlusion. Custom 3D-printed splints and guides are fabricated from the plan and used in the operating room.
                    </p>

