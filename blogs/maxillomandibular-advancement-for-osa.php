                    <h2 id="what-is-osa" class="scroll-mt-24">What is OSA and Why Your Jaw Matters</h2>

                    <p>
                        Obstructive sleep apnoea is a condition in which your upper airway collapses repeatedly during sleep. Each collapse pauses your breathing, drops your oxygen, and jerks you briefly awake.
                    </p>

                    <p>
                        Over time, OSA raises your risk of high blood pressure, heart attack, stroke, type 2 diabetes, daytime fatigue, and motor-vehicle accidents. It is more than snoring. It is a serious medical disorder.
                    </p>

                    <p>
                        The root cause is almost always anatomical. When the jaws sit too far back, the tongue and soft tissues of the throat have nowhere to go during sleep. They fall backward and block the airway.
                    </p>

                    <p>
                        This is why the position of your maxilla and mandible is central to airway size. Bringing both jaws forward physically opens the space behind the tongue. That simple anatomical idea is the foundation of <a href="/blogs/can-jaw-surgery-help-with-sleep-apnea/">jaw surgery for sleep apnoea</a>.
                    </p>

