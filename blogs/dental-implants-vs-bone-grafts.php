                    <h2 id="what-is-implant" class="scroll-mt-24">What Is a Dental Implant?</h2>
                    <p>
                        A dental implant is a small titanium screw that replaces the root of a missing tooth. The surgeon places it directly into the jawbone, where it fuses with the surrounding bone through a process called osseointegration.
                    </p>

                    <p>
                        Once the implant is stable, a connector piece called an abutment is fixed on top. A custom-made crown is then attached to the abutment to complete the visible tooth.
                    </p>

                    <p>
                        The result looks, feels, and functions like a natural tooth. With proper care, dental implants offer a long-term solution for single, multiple, or full-arch tooth replacement.
                    </p>

                    <div class="aspect-[16/9] w-full rounded-2xl overflow-hidden shadow-lg border border-surface-container-high my-10"><img alt="Dental implant components" class="w-full h-full object-cover" src="https://picsum.photos/1200/675?random=181"/></div>

                    <h2 id="why-bone-matters" class="scroll-mt-24">Why Bone Matters for Implant Success</h2>
                    <p>
                        An implant needs adequate bone volume and density to anchor securely. Without enough bone, the implant cannot integrate properly and may fail over time.
                    </p>

                    <p>
                        Tooth loss is the most common reason bone shrinks. The jawbone depends on the stimulation it receives from a tooth root. Once a tooth is gone, that stimulation stops, and the bone begins to resorb.
                    </p>

                    <p>
                        Teeth are lost for several reasons. Advanced decay, severe gum disease, traumatic injuries, and congenital absence (such as missing lateral incisors) all leave a gap that the bone will gradually fill in or shrink away from.
                    </p>

                    <p>
                        The longer a tooth has been missing, the more bone you tend to lose. Many patients we see at Gnathos Facial Surgery arrive years after an extraction, often unaware that the ridge beneath has thinned considerably. Recognising the <a href="/blogs/what-are-the-symptoms-of-jaw-disease/" class="text-secondary hover:underline">symptoms of jaw disease</a> early can prevent this kind of silent bone loss.
                    </p>

                    <p>
                        In the upper jaw, the sinus cavity sits just above the back teeth. When those teeth are lost, the sinus may expand downward into the space, leaving little bone for implant placement.
                    </p>

                    <h3>When Is Bone Insufficient?</h3>
                    <p>
                        Bone is typically considered insufficient for an implant when its height is below 6–8 mm or its width is under 5 mm. Common causes include long-standing tooth loss, severe periodontitis, trauma from <a href="/blogs/broken-jaw-symptoms/" class="text-secondary hover:underline">broken jaw symptoms</a> that went untreated, long-term denture wear, cysts, and tumour resections.
                    </p>

