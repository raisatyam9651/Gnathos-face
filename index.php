function handleContactSubmit(e) {
  e.preventDefault();
  const form = e.target;
  const btn = document.getElementById('contact-submit');
  const success = document.getElementById('form-success');
  
  btn.disabled = true;
  btn.innerHTML = '<span class="material-symbols-outlined animate-spin" style="font-size:18px;">progress_activity</span> Sending…';
  
  // Create FormData and map to the old form structure for Formester compatibility
  const formData = new FormData();
  
  const fullName = form.querySelector('[name="name"]').value.trim();
  const nameParts = fullName.split(/\s+/);
  const firstName = nameParts[0] || '';
  const lastName = nameParts.slice(1).join(' ') || '';
  
  formData.append('FirstName', firstName);
  formData.append('LastName', lastName);
  formData.append('Email', form.querySelector('[name="email"]').value);
  formData.append('PhoneNumber', form.querySelector('[name="phone"]').value);
  
  const treatment = form.querySelector('[name="treatment"]').value;
  const messageVal = form.querySelector('[name="message"]').value;
  const fullMessage = (treatment ? `Treatment of Interest: ${treatment}\n\n` : '') + messageVal;
  formData.append('Message', fullMessage);
  
  // Also send the raw new fields just in case they are mapped directly in Formester
  formData.append('name', fullName);
  formData.append('phone', form.querySelector('[name="phone"]').value);
  formData.append('email', form.querySelector('[name="email"]').value);
  formData.append('treatment', treatment);
  formData.append('message', messageVal);

  fetch('https://app.formester.com/forms/O0tc1x4O7/submissions', {
    method: 'POST',
    body: formData,
    mode: 'no-cors'
  })
  .then(response => {
    btn.classList.add('hidden');
    success.classList.remove('hidden');
  })
  .catch(error => {
    console.error('Error submitting form:', error);
    btn.disabled = false;
    btn.innerHTML = '<span class="material-symbols-outlined" style="font-size:18px;">send</span> Send Message';
    alert('There was an error sending your message. Please try again.');
  });
}
