<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What is the difference between skin graft surgery and skin flap surgery?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Skin graft surgery involves transplanting skin from a donor site to cover the wound - the skin is completely detached and relies on the underlying tissue for blood supply. Skin flap surgery moves tissue with its own blood supply still intact (either pedicled or free with microvascular connection). Flaps generally provide better color and texture match and are preferred for visible areas and complex defects.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
