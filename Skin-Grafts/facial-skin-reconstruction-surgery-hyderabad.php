</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Our goal is to achieve the most natural-looking result possible. The final appearance depends on factors like the size and location of the defect, the technique used, and individual healing. We carefully match skin color and texture, and our surgeons have extensive experience in achieving aesthetically pleasing results. Some patients may benefit from additional procedures like scar revision for optimal outcomes.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How long does recovery take after facial skin reconstruction surgery?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Recovery varies depending on the type and extent of reconstruction. Initial healing typically takes 2-3 weeks, during which you'll need to avoid strenuous activities. Most patients can return to light activities within 1-2 weeks. The graft or flap settles over 4-6 weeks, and final results with scar maturation may take 6-12 months. Your surgeon will provide a detailed recovery plan specific to your procedure.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Will I have visible scars after the surgery?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    All surgery creates some scarring, but our surgeons use techniques to minimize visibility. Incisions are placed along natural skin lines and creases whenever possible. The donor site for skin grafts will also leave a scar, though we select sites that can be hidden. Over time, scars typically fade and can be further improved with scar management treatments or revision surgery if needed.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
