</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Yes, burn reconstruction is a specialized area of facial skin reconstruction surgery. After initial burn healing, scar contractures and deformities can be released and reconstructed using skin grafts, flaps, or tissue expansion techniques. Burn reconstruction often requires staged procedures and may begin months after the initial injury once the burn wounds have fully healed and scar maturation has begun.
                </div>
