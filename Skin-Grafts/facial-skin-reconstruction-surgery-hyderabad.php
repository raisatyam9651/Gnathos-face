<p class="font-body-lg text-body-lg text-on-surface-variant max-w-2xl mx-auto">
                Our surgeons utilize a range of advanced techniques tailored to each patient's specific needs and reconstruction goals.
            </p>
</div>
<div class="max-w-4xl mx-auto bg-surface-container-lowest rounded-xl shadow-sm border border-surface-variant overflow-hidden">
<div class="divide-y divide-surface-variant">
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Skin Grafting</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Transplantation</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">Skin transplant surgery involves harvesting skin from a donor site and transplanting it to cover the wound. Split-thickness grafts are thinner and used for larger areas, while full-thickness grafts provide better color and texture match for visible areas.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Split-thickness skin grafts for extensive defects</li>
<li>Full-thickness skin grafts for aesthetic areas</li>
<li>Meshed grafts for large surface areas</li>
</ul>
</div>
</div>
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Local Flaps</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Tissue Rearrangement</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">Local flap surgery moves adjacent tissue with its blood supply intact to reconstruct the defect. This technique is ideal for areas where skin color and texture match is important, providing superior aesthetic results compared to skin grafts.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Advancement flaps for linear defects</li>
<li>Rotation flaps for curved defects</li>
<li>Transposition flaps for irregular shapes</li>
</ul>
</div>
</div>
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Regional & Free Flaps</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Complex Reconstruction</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">For complex defects, particularly those involving underlying structures, regional or free flap surgery may be required. This involves transferring tissue from another body area with its blood supply, connected using microvascular techniques.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Pedicle flaps for moderate defects</li>
<li>Free tissue transfer for complex reconstructions</li>
<li>Composite flaps for defects with bone involvement</li>
</ul>
</div>
</div>
</div>
