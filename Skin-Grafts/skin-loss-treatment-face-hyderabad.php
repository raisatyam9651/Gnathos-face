</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">For complex defects, especially those involving exposed bone, cartilage, or deep structures, flap reconstruction is preferred. Tissue with its blood supply is moved to cover the defect, providing better coverage and healing potential.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Superior blood supply and healing</li>
<li>Better for deep or complex defects</li>
