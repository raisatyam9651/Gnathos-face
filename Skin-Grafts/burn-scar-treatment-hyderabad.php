<p class="text-on-surface-variant">Tightening of the skin that can restrict movement, particularly when scars cross joints. Contractures often require surgical release.</p>
</div>
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant hover-lift">
<span class="material-symbols-outlined text-4xl text-secondary mb-4 icon-fill-1">palette</span>
