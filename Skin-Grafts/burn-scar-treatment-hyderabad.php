<h3 class="font-headline-sm text-xl text-primary mb-3">Keloid Scars</h3>
<p class="text-on-surface-variant">Raised scars that extend beyond the original wound boundaries. They can continue to grow over time and may require specialized treatment approaches.</p>
</div>
