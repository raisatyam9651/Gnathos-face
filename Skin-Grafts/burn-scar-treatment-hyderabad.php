</div>
<div class="bg-surface-container-lowest p-8 rounded-xl shadow-sm border border-surface-variant hover-lift">
<span class="material-symbols-outlined text-4xl text-secondary mb-4 icon-fill-1">texture</span>
<h3 class="font-headline-sm text-xl text-primary mb-3">Mature Scars</h3>
<p class="text-on-surface-variant">Established scars that have completed the healing process. These may benefit from revision surgery or camouflage techniques.</p>
</div>
