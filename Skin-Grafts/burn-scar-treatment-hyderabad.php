<div class="space-y-4">
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    When is the right time to start burn scar treatment?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    The timing depends on the type of treatment. Generally, we wait until the scar has matured, which typically takes 12-18 months after the burn injury. However, scar contractures affecting function may need earlier intervention. During the waiting period, conservative treatments like silicone therapy and pressure garments can be started early to optimize scar outcome.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can burn scars be completely removed?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Unfortunately, scars cannot be completely erased. However, burn scar treatment can significantly improve their appearance and function. Surgical techniques can reposition scars into less visible locations, release contractures, and replace burn tissue with better-matched skin. The goal is to make scars less noticeable and restore function, not to achieve completely invisible skin.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How long does recovery take after scar revision surgery?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Recovery varies based on the procedure. Simple scar revision may require 1-2 weeks for initial healing. More extensive procedures like contracture release with skin grafting require 3-4 weeks for the graft to take and several months for complete remodeling. Your surgeon will provide a detailed recovery timeline specific to your procedure. Activity restrictions are typically needed for 4-6 weeks.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Will insurance cover burn scar treatment?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Burn scar treatment is often covered by health insurance when it addresses functional problems like contractures restricting movement, or when the original injury was accidental. Purely cosmetic procedures may not be covered. We recommend checking with your insurance provider and can assist you in understanding your coverage and documentation requirements.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What is tissue expansion and is it right for me?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Tissue expansion is a technique where a balloon expander is surgically placed under healthy skin near the burn scar. Over several weeks, saline is injected to gradually expand the skin, creating extra tissue. This expanded skin is then used to replace the burn scar, providing color and texture-matched results. It's particularly useful for large burn areas but requires multiple procedures and a commitment to the expansion process.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How many treatments will I need?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
