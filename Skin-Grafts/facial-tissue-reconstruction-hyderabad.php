<!-- Reconstruction Techniques -->
<section class="py-section-gap bg-surface-container-low">
<div class="max-w-container-max mx-auto px-margin-mobile md:px-margin-desktop">
<div class="text-center mb-12">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Reconstruction Techniques</h2>
<p class="font-body-lg text-body-lg text-on-surface-variant max-w-2xl mx-auto">
                We utilize various reconstructive techniques based on defect characteristics and patient factors.
            </p>
</div>
<div class="max-w-4xl mx-auto bg-surface-container-lowest rounded-xl shadow-sm border border-surface-variant overflow-hidden">
<div class="divide-y divide-surface-variant">
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Local Flap</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Tissue Rearrangement</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">Adjacent tissue is rearranged to fill a nearby defect. Various designs including advancement, rotation, and transposition flaps are used depending on the defect shape and location. This provides tissue with similar color and texture.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Advancement flaps for linear defects</li>
<li>Rotation flaps for curved defects</li>
<li>Transposition flaps for complex shapes</li>
</ul>
</div>
</div>
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Regional Flap</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Pedicled Tissue</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">Tissue from nearby regions is moved on a pedicle containing blood vessels to provide robust coverage. These flaps are reliable and provide tissue with good blood supply for areas with compromised underlying tissue.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Pedicled flap reliability</li>
<li>Good blood supply for healing</li>
<li>Suitable for complex defects</li>
</ul>
</div>
</div>
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Free Flap</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Microvascular</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">Tissue is transferred from a distant site (such as arm, leg, or abdomen) with its blood vessels surgically connected to vessels in the face using microvascular technique. This allows precise tissue matching for complex or large defects.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Precise color and texture matching</li>
<li>Option for large defects</li>
<li>Composite tissue including bone if needed</li>
</ul>
</div>
</div>
