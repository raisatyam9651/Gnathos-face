                    How many surgeries will I need for burn reconstruction?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    The number of surgeries depends on the extent of burn scarring. Simple scar revisions may require one procedure. Complex reconstructions, especially those involving tissue expansion, often require multiple staged procedures over several months to years. Your surgeon will provide an estimated treatment timeline during your consultation.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Will burn reconstruction remove all my scars?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Burn scars cannot be completely removed. The goal of reconstruction is to improve function and make scars less visible. Reconstruction can replace burn tissue with better-matched skin, release contractures, and reposition scars into less visible locations. Most patients achieve significant improvement, but realistic expectations are important.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    What is tissue expansion and is it right for me?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Tissue expansion involves surgically placing a balloon expander under healthy skin near the burn scar. Over several weeks, saline is injected to gradually expand the skin, creating extra tissue. This expanded skin is then used to replace the burn scar. It's particularly useful for large burn areas where color and texture matching are important, but it requires multiple procedures and a commitment to the expansion process.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Will insurance cover burn reconstruction surgery?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Burn reconstruction surgery is typically covered by health insurance when addressing functional problems like contractures or when treating the aftermath of accidental burns. Purely cosmetic procedures may not be covered. If your burn resulted from a workplace accident or other covered incident, additional coverage may be available. Check with your insurer for specific coverage details.
                </div>
</details>
