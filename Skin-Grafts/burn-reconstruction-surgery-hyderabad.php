<div class="text-center mb-12">
<h2 class="font-headline-md text-headline-md text-primary mb-4">Burn Reconstruction Techniques</h2>
<p class="font-body-lg text-body-lg text-on-surface-variant max-w-2xl mx-auto">
                We utilize advanced reconstruction techniques tailored to each patient's specific burn injury and reconstruction needs.
            </p>
</div>
<div class="max-w-4xl mx-auto bg-surface-container-lowest rounded-xl shadow-sm border border-surface-variant overflow-hidden">
<div class="divide-y divide-surface-variant">
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Contracture Release</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Functional</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">Burn scar contractures limiting movement are released by dividing the tight scar tissue. The resulting defect is covered with skin grafts or local flaps to restore function. Multiple Z-plasty techniques may redistribute tension and improve both function and appearance.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Linear contracture release</li>
<li>Multiple Z-plasty techniques</li>
<li>Skin graft or flap coverage</li>
</ul>
</div>
</div>
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Skin Grafting</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Coverage</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">Skin graft surgery involves transplanting skin from a donor site to replace burned tissue. Split-thickness grafts are commonly used for large areas, while full-thickness grafts provide better match for visible facial areas. Meshed grafts allow drainage over large surface areas.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Split-thickness skin grafts</li>
<li>Full-thickness skin grafts</li>
<li>Meshed graft techniques</li>
</ul>
</div>
</div>
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Tissue Expansion</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Advanced</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">For large burn areas, tissue expansion creates additional skin that matches in color and texture. A balloon expander is placed under nearby healthy skin and gradually inflated over weeks. The expanded skin is then used to replace the burn scar, providing superior aesthetic results.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Ideal for large burn areas</li>
<li>Color and texture-matched results</li>
<li>Staged reconstruction procedure</li>
</ul>
</div>
</div>
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Flap Surgery</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Complex</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">For burn defects with exposed underlying structures or in areas requiring robust coverage, flap surgery provides tissue with its own blood supply. Local flaps, regional flaps, or free flaps may be used depending on the defect size and location.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Local and regional flaps</li>
<li>Free microvascular flaps</li>
<li>Composite tissue transfer</li>
</ul>
</div>
