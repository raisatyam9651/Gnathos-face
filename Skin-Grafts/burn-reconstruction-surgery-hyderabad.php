<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    When can burn scars be reconstructed?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">expand_more</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Burn reconstruction is typically performed after scar maturation is complete, usually 12-18 months after the burn injury. However, functional problems like contractures limiting movement may need earlier intervention. During the waiting period, conservative treatments like pressure therapy and silicone can help optimize scar outcome. Your surgeon will determine the appropriate timing for your specific situation.
