</div>
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Z-Plasty & W-Plasty</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Advanced Revision</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">Z-plasty involves creating Z-shaped flaps to redistribute scar tension and change scar direction, making it less visible. W-plasty creates a W-shaped pattern that breaks up the scar line for camouflage. Both are effective for widened or contracture scars.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Direction change for scar camouflage</li>
<li>Contracture release and function improvement</li>
<li>Natural skin line alignment</li>
</ul>
</div>
</div>
<div class="p-6 md:p-8 flex flex-col md:flex-row gap-6">
<div class="md:w-1/4 shrink-0">
