<div class="md:w-1/4 shrink-0">
<h4 class="font-headline-sm text-lg text-primary">Scar Excision</h4>
<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Simple Revision</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">The scarred tissue is surgically removed and the wound is closed with careful technique to minimize tension and align with natural skin creases. This creates a new, finer scar that is less visible than the original.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Layered closure for minimal tension</li>
<li>Placement along natural skin lines</li>
<li>Fine suture technique</li>
</ul>
