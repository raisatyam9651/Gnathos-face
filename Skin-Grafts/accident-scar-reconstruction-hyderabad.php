<span class="text-sm font-semibold text-secondary uppercase tracking-wider">Complex Cases</span>
</div>
<div class="md:w-3/4 text-on-surface-variant">
<p class="mb-3">For larger accident scars with tissue loss, skin graft surgery or local flap reconstruction may be necessary. This involves replacing the scarred tissue with healthier skin that matches better in color and texture.</p>
<ul class="list-disc list-inside space-y-1 text-sm">
<li>Full-thickness skin grafts</li>
<li>Local and regional flap procedures</li>
<li>Composite tissue reconstruction</li>
